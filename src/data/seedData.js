export const SCORE_WEIGHTS = {
  impact: 0.35,
  strategicFit: 0.3,
  feasibility: 0.2,
  risk: 0.15,
};

export function calcWeightedScore({ impact, strategicFit, feasibility, risk }) {
  const score =
    impact * SCORE_WEIGHTS.impact +
    strategicFit * SCORE_WEIGHTS.strategicFit +
    feasibility * SCORE_WEIGHTS.feasibility +
    risk * SCORE_WEIGHTS.risk;
  return Math.round(score * 10) / 10;
}

export function tierFromScore(score) {
  if (score >= 4.2) return 'P1';
  if (score >= 3.4) return 'P2';
  if (score >= 2.6) return 'P3';
  return 'P4';
}

